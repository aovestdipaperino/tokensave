    #[test]
    fn precedence_env_project_global_benchmark_default() {
        use CpuUsage::{Balanced, Low, Performance};
        use CpuUsageSource as S;
        let never_global = || -> ResourcePreferences { panic!("global config read needlessly") };
        let never_bench = || -> Option<CpuUsage> { panic!("benchmark read needlessly") };

        assert_eq!(
            resolve_with(Some(Low), Some(Performance), never_global, never_bench),
            (Low, S::Environment)
        );
        assert_eq!(
            resolve_with(None, Some(Low), never_global, never_bench),
            (Low, S::Project),
            "a project pin beats a benchmark recommending more"
        );
        assert_eq!(
            resolve_with(None, None, || prefs(Some(Low), true), never_bench),
            (Low, S::GlobalConfig)
        );
        assert_eq!(
            resolve_with(None, None, || prefs(None, true), || Some(Performance)),
            (Performance, S::Benchmark)
        );
        assert_eq!(
            resolve_with(None, None, || prefs(None, true), || None),
            (Balanced, S::Default)
        );
        assert_eq!(
            resolve_with(None, None, || prefs(None, false), never_bench),
            (Balanced, S::Default),
            "a disabled benchmark is not consulted"
        );
    }
