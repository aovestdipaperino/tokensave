    #[test]
    fn simultaneous_callers_measure_once_and_share_the_result() {
        let dir = Arc::new(tempfile::tempdir().unwrap());
        let calls = Arc::new(AtomicUsize::new(0));
        let current = host(16, 64);
        let handles: Vec<_> = (0..8)
            .map(|_| {
                let dir = Arc::clone(&dir);
                let calls = Arc::clone(&calls);
                std::thread::spawn(move || {
                    ensure_in(
                        dir.path(),
                        ON,
                        Trigger::Automatic,
                        || current,
                        |_| {
                            calls.fetch_add(1, Ordering::SeqCst);
                            // Long enough for the other callers to queue on the lock.
                            std::thread::sleep(std::time::Duration::from_millis(100));
                            measured(current, 14.0)
                        },
                    )
                })
            })
            .collect();
        let outcomes: Vec<_> = handles.into_iter().map(|h| h.join().unwrap()).collect();
        assert_eq!(calls.load(Ordering::SeqCst), 1, "{outcomes:?}");
        assert!(outcomes.iter().all(|o| profile(o) == CpuUsage::Performance));
    }

    #[test]
    fn concurrent_readers_never_see_a_partial_file() {
        let dir = Arc::new(tempfile::tempdir().unwrap());
        let current = host(8, 16);
        let calls = AtomicUsize::new(0);
        let m = measured(current, 6.0);
        run(dir.path(), ON, Trigger::Force, current, m, &calls);
        let stop = Arc::new(AtomicBool::new(false));
        let reader = {
            let (dir, stop) = (Arc::clone(&dir), Arc::clone(&stop));
            std::thread::spawn(move || {
                let mut reads = 0u32;
                while !stop.load(Ordering::Relaxed) || reads == 0 {
                    assert!(
                        matches!(check_in(dir.path(), &current), CacheStatus::Valid(_)),
                        "a reader saw a partial or missing file"
                    );
                    reads += 1;
                }
                reads
            })
        };
        for speedup in [6.0, 7.0, 1.5, 6.5] {
            let m = measured(current, speedup);
            run(dir.path(), ON, Trigger::Force, current, m, &calls);
        }
        stop.store(true, Ordering::Relaxed);
        assert!(reader.join().unwrap() > 0);
    }

